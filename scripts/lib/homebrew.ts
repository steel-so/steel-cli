import { parseChecksums } from './checksums.js'
import { assetName, TARGETS } from './targets.js'

export interface FormulaInput {
  version: string
  /** Contents of the release's SHA256SUMS. */
  checksums: string
  /** `owner/repo` that hosts the release assets. */
  repository: string
}

function asset(
  input: FormulaInput,
  sums: Map<string, string>,
  id: string,
): { url: string; sha256: string } {
  const target = TARGETS.find((candidate) => candidate.id === id)
  if (!target) throw new Error(`unknown target ${id}`)
  const name = assetName(target)
  const sha256 = sums.get(name)
  if (!sha256) throw new Error(`SHA256SUMS has no entry for ${name}`)
  return {
    url: `https://github.com/${input.repository}/releases/download/v${input.version}/${name}`,
    sha256,
  }
}

/** The Homebrew formula for `steel-so/homebrew-tap` (`Formula/steel.rb`). */
export function renderFormula(input: FormulaInput): string {
  if (!/^\d+\.\d+\.\d+$/.test(input.version)) {
    throw new Error(`not a stable version: ${input.version}`)
  }
  const sums = parseChecksums(input.checksums)
  const block = (id: string, indent: string) => {
    const { url, sha256 } = asset(input, sums, id)
    return `${indent}url "${url}"\n${indent}sha256 "${sha256}"`
  }
  return `# Generated by steel-so/steel-cli (scripts/release.ts formula). Do not edit.
class Steel < Formula
  desc "Steel no terminal: login, API v1, webhooks e MCP"
  homepage "https://github.com/${input.repository}"
  version "${input.version}"
  license :cannot_represent

  on_macos do
    on_arm do
${block('darwin-arm64', '      ')}
    end
    on_intel do
${block('darwin-x64', '      ')}
    end
  end

  on_linux do
    on_arm do
${block('linux-arm64', '      ')}
    end
    on_intel do
${block('linux-x64', '      ')}
    end
  end

  def install
    bin.install "steel"
    generate_completions_from_executable(bin/"steel", "completion")
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/steel --version")
  end
end
`
}
