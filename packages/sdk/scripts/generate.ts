/**
 * Generates `src/generated/schema.ts` from the Steel public API v1 document.
 *
 *   pnpm generate                      # default source (see below)
 *   pnpm generate <path-or-url>        # explicit source
 *   pnpm generate:check                # CI: committed output is up to date
 *
 * Source precedence: CLI argument, `STEEL_OPENAPI_SOURCE`, the sibling Steel
 * checkout (`../steel/public/openapi.v1.json` next to this repo), then the
 * contract-shaped fixture in `openapi/fixture.v1.json`. The document used is
 * snapshotted to `openapi/openapi.v1.json` so `--check` is reproducible.
 */
import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const here = dirname(fileURLToPath(import.meta.url))
const pkgRoot = resolve(here, '..')
const repoRoot = resolve(pkgRoot, '../..')
const snapshotPath = resolve(pkgRoot, 'openapi/openapi.v1.json')
const fixturePath = resolve(pkgRoot, 'openapi/fixture.v1.json')
const outputPath = resolve(pkgRoot, 'src/generated/schema.ts')
const siblingSteel = resolve(repoRoot, '../steel/public/openapi.v1.json')

async function loadSource(source: string): Promise<string> {
  if (/^https?:\/\//.test(source)) {
    const response = await fetch(source)
    if (!response.ok) {
      throw new Error(`GET ${source} failed with ${response.status}`)
    }
    return response.text()
  }
  return readFile(resolve(process.cwd(), source), 'utf8')
}

function pickSource(arg: string | undefined): string {
  if (arg) return arg
  const fromEnv = process.env.STEEL_OPENAPI_SOURCE
  if (fromEnv) return fromEnv
  if (existsSync(siblingSteel)) return siblingSteel
  return fixturePath
}

async function render(documentText: string): Promise<string> {
  const document = JSON.parse(documentText)
  const ast = await openapiTS(document, {
    alphabetize: true,
    exportType: true,
  })
  const version = document.info?.version ?? 'unknown'
  const header = [
    '/**',
    ' * Generated by packages/sdk/scripts/generate.ts. Do not edit.',
    ` * Steel API v1 document version: ${version}`,
    ' */',
    '',
  ].join('\n')
  return header + astToString(ast)
}

async function main() {
  const args = process.argv.slice(2)
  const check = args.includes('--check')
  const sourceArg = args.find((arg) => !arg.startsWith('--'))

  if (check) {
    const snapshot = await readFile(snapshotPath, 'utf8')
    const expected = await render(snapshot)
    const current = existsSync(outputPath)
      ? await readFile(outputPath, 'utf8')
      : ''
    if (expected !== current) {
      console.error(
        'src/generated/schema.ts is out of date with openapi/openapi.v1.json. Run `pnpm --filter @steel-so/sdk generate`.',
      )
      process.exit(1)
    }
    console.log('SDK schema is up to date.')
    return
  }

  const source = pickSource(sourceArg)
  const text = await loadSource(source)
  const normalized = `${JSON.stringify(JSON.parse(text), null, 2)}\n`
  await mkdir(dirname(outputPath), { recursive: true })
  await writeFile(snapshotPath, normalized)
  await writeFile(outputPath, await render(normalized))
  console.log(`Generated the SDK schema from ${source}`)
}

main().catch((error: unknown) => {
  console.error(error)
  process.exit(1)
})
